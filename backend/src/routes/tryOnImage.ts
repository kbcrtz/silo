import { createHash } from "node:crypto";
import type { FastifyInstance } from "fastify";
import { z } from "zod";
import { isColor, listingFacts, normalizeProduct } from "../catalog/normalize.ts";
import { HttpError } from "../errors.ts";
import type { Gate } from "../guard.ts";
import type { Enrich } from "../services/listingInsights.ts";
import type { Catalog } from "../services/shopifyCatalog.ts";
import { bodyWords, FIT_ORDER, FIT_VERSION, fitPrompt, Guide, guideImage, TEMPLATE_VERSION, tryOnPrompt, type TryOn } from "../services/tryOnImage.ts";
import { jsonParam, Selected, SelectedParam } from "./catalog.ts";

const Id = z.string().regex(/^gid:\/\/shopify\/p\/[A-Za-z0-9]+$/);
const Category = z.enum(["top", "bottom", "dress", "outerwear"]);
/** A whole fit: one piece of each kind, and a dress takes the place of the top and bottoms. */
const Fit = z
  .array(z.strictObject({ id: Id, category: Category, selected: Selected.optional() }))
  .min(2)
  .max(3)
  .refine((pieces) => {
    const kinds = pieces.map((p) => p.category);
    return new Set(kinds).size === kinds.length && !(kinds.includes("dress") && (kinds.includes("top") || kinds.includes("bottom")));
  });
const Query = z
  .strictObject({
    id: Id.optional(),
    fit: jsonParam(3000, Fit).optional(),
    shopFor: z.enum(["womens", "mens", "both"]).default("both"),
    selected: SelectedParam.optional(),
    guide: jsonParam(12_000, Guide).optional(),
    category: Category.optional(),
  })
  // One product, or a fit drawn on the shopper's body.
  .refine((q) => (q.id ? !q.fit : q.fit && q.guide));

/**
 * GET /catalog/tryon-image?id=<gid>&shopFor=&selected=<JSON>&guide=<JSON>&category=: a
 * full-body mannequin wearing the product, generated by Gemini from the store
 * photo with a fixed template, then saved so each product, color, department
 * and body is generated once. `guide` is the app's drawn mannequin body, so the
 * image has the shopper's proportions. With `fit=<JSON>` (2-3 pieces, each
 * {id, category, selected?}) instead of `id`, one image of the whole fit on
 * the guide's body. Returns image/jpeg.
 */
export async function tryOnImageRoute(
  app: FastifyInstance,
  {
    catalog,
    enrich,
    tryOn,
    tryOnGate,
    anonymousTryOnGate,
  }: { catalog: Catalog; enrich?: Enrich; tryOn?: TryOn; tryOnGate?: Gate; anonymousTryOnGate?: Gate },
) {
  app.get("/catalog/tryon-image", async (req, reply) => {
    const started = performance.now();
    // Counts only: no product photos or prompts.
    const diag: Record<string, unknown> = {};
    const entered: Gate[] = [];
    try {
      if (!tryOn) throw new HttpError("tryon_unavailable", 503);
      const query = Query.safeParse(req.query);
      if (!query.success) throw new HttpError("invalid_request", 400);
      const { fit, shopFor, guide } = query.data;
      const pieces = fit
        ? fit.toSorted((a, b) => FIT_ORDER.indexOf(a.category) - FIT_ORDER.indexOf(b.category))
        : [{ id: query.data.id!, category: query.data.category, selected: query.data.selected }];
      // Without the shopper's color, Shopify answers with the store's default variant and its photo, often another color.
      // Size doesn't change the photo, so only the color is sent and keyed.
      const colors = pieces.map((p) => p.selected?.filter((c) => isColor(c.name)) ?? []);
      const body = guide ? [createHash("sha256").update(JSON.stringify(guide)).digest("hex").slice(0, 16)] : [];
      const label = (i: number) => colors[i].map((c) => c.label.toLowerCase());
      const key = (
        fit
          ? ["fit", shopFor, ...pieces.map((p, i) => [p.category, p.id, ...label(i)].join(":")), ...body, `v${FIT_VERSION}`]
          : [pieces[0].id, shopFor, ...label(0), ...body, `v${TEMPLATE_VERSION}`]
      ).join("|");

      const saved = await tryOn.store.get(key).catch(() => null);
      diag.saved = Boolean(saved);
      if (fit) diag.pieces = pieces.length;
      if (saved) return reply.header("content-type", "image/jpeg").header("cache-control", "private, max-age=86400").send(saved);

      // Generation is billed: a budget per signed-in user, and per IP across anonymous logins.
      const gates: [Gate | undefined, string][] = [[tryOnGate, req.userId ?? req.ip], [req.anonymous ? anonymousTryOnGate : undefined, req.ip]];
      for (const [gate, key] of gates) {
        if (!gate) continue;
        const slot = gate.tryEnter(key);
        if (slot !== "ok") throw new HttpError(slot === "rate" ? "rate_limited" : "busy", slot === "rate" ? 429 : 503);
        entered.push(gate);
      }

      const found = await Promise.all(
        pieces.map(async (p, i) => {
          const raw = await catalog.getProduct(p.id, colors[i].length ? colors[i] : undefined);
          const product = raw ? normalizeProduct(raw, undefined, { detail: true }) : null;
          if (!raw || !product) throw new HttpError("product_not_found", 404);
          const photoUrl = product.images?.[0]?.url ?? product.image?.url;
          if (!photoUrl) throw new HttpError("no_photo", 422);
          return { raw, product, photoUrl };
        }),
      );
      // The app sends the category the feed's listing reader already found; only older builds need the reader here (about 1 s).
      const { category } = query.data;
      const [photos, insight] = await Promise.all([
        Promise.all(found.map((f) => tryOn.fetchPhoto(f.photoUrl))),
        fit || category || !enrich ? null : enrich([listingFacts(found[0].raw)!]).then(([i]) => i, () => null),
      ]);
      if (insight?.clothing === false) throw new HttpError("not_clothing", 422);
      const cut = insight?.cut;
      const prompt = fit
        ? fitPrompt({
            pieces: pieces.map((p, i) => ({ category: p.category!, title: found[i].product.title })),
            department: shopFor,
            build: bodyWords(guide!),
          })
        : tryOnPrompt({
            category: category ?? cut?.category ?? "top",
            department: shopFor,
            cut: cut && [`${cut.silhouette} fit`, `${cut.length} length`, cut.sleeve && `${cut.sleeve} sleeves`].filter(Boolean).join(", "),
            title: found[0].product.title,
            build: guide && bodyWords(guide),
          });

      diag.prepMs = Math.round(performance.now() - started); // Shopify and photos, before Gemini
      const image = await tryOn.generate(photos, prompt, guide && (await guideImage(guide)));
      diag.generated = true;
      // Saved after answering, so the shopper doesn't wait on the database; a failed save means the next view generates again.
      void tryOn.store.put(key, image, "gemini").catch(() => {});
      return reply.header("content-type", "image/jpeg").header("cache-control", "private, max-age=86400").send(image);
    } catch (e) {
      const known = e instanceof HttpError ? e : null;
      if (!known) req.log.error({ errorName: (e as Error).name }, "tryon_unexpected");
      const err = known ?? new HttpError("internal_error", 500);
      diag.error = err.code;
      if (err.providerStatus) diag.providerStatus = err.providerStatus;
      return reply.code(err.status).send({ error: err.code });
    } finally {
      for (const gate of entered) gate.leave();
      diag.durationMs = Math.round(performance.now() - started);
      req.log.info({ tryOnImage: diag }, "tryon_image");
    }
  });
}
