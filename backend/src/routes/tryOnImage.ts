import type { FastifyInstance } from "fastify";
import { z } from "zod";
import { isColor, listingFacts, normalizeProduct } from "../catalog/normalize.ts";
import { HttpError } from "../errors.ts";
import type { Gate } from "../guard.ts";
import type { Enrich } from "../services/listingInsights.ts";
import type { Catalog } from "../services/shopifyCatalog.ts";
import { TEMPLATE_VERSION, tryOnPrompt, type TryOn } from "../services/tryOnImage.ts";
import { SelectedParam } from "./catalog.ts";

const Query = z.strictObject({
  id: z.string().regex(/^gid:\/\/shopify\/p\/[A-Za-z0-9]+$/),
  shopFor: z.enum(["womens", "mens", "both"]).default("both"),
  selected: SelectedParam.optional(),
});

/**
 * GET /catalog/tryon-image?id=<gid>&shopFor=&selected=<JSON>: a full-body
 * mannequin wearing the product, generated by Gemini from the store photo
 * with a fixed template, then saved so each product, color and department is
 * generated once. Returns image/jpeg.
 */
export async function tryOnImageRoute(
  app: FastifyInstance,
  { catalog, enrich, tryOn, tryOnGate }: { catalog: Catalog; enrich?: Enrich; tryOn?: TryOn; tryOnGate?: Gate },
) {
  app.get("/catalog/tryon-image", async (req, reply) => {
    const started = performance.now();
    // Counts only: no product photos or prompts.
    const diag: Record<string, unknown> = {};
    let entered = false;
    try {
      if (!tryOn) throw new HttpError("tryon_unavailable", 503);
      const query = Query.safeParse(req.query);
      if (!query.success) throw new HttpError("invalid_request", 400);
      const { id, shopFor } = query.data;
      // Without the shopper's color, Shopify answers with the store's default variant and its photo, often another color.
      // Size doesn't change the photo, so only the color is sent and keyed.
      const color = query.data.selected?.filter((c) => isColor(c.name)) ?? [];
      const key = [id, shopFor, ...color.map((c) => c.label.toLowerCase()), `v${TEMPLATE_VERSION}`].join("|");

      const saved = await tryOn.store.get(key).catch(() => null);
      diag.saved = Boolean(saved);
      if (saved) return reply.header("content-type", "image/jpeg").header("cache-control", "private, max-age=86400").send(saved);

      // Generation is billed: a budget per signed-in user.
      if (tryOnGate) {
        const slot = tryOnGate.tryEnter(req.userId ?? req.ip);
        if (slot !== "ok") throw new HttpError(slot === "rate" ? "rate_limited" : "busy", slot === "rate" ? 429 : 503);
        entered = true;
      }

      const raw = await catalog.getProduct(id, color.length ? color : undefined);
      const product = raw ? normalizeProduct(raw, undefined, { detail: true }) : null;
      if (!raw || !product) throw new HttpError("product_not_found", 404);
      const photoUrl = product.images?.[0]?.url ?? product.image?.url;
      if (!photoUrl) throw new HttpError("no_photo", 422);

      // The listing reader says what kind of item it is, which picks the counterpart.
      const [insight] = enrich ? await enrich([listingFacts(raw)!]).catch(() => [null]) : [null];
      if (insight?.clothing === false) throw new HttpError("not_clothing", 422);
      const cut = insight?.cut;
      const prompt = tryOnPrompt({
        category: cut?.category ?? "top",
        department: shopFor,
        cut: cut && [`${cut.silhouette} fit`, `${cut.length} length`, cut.sleeve && `${cut.sleeve} sleeves`].filter(Boolean).join(", "),
      });

      const image = await tryOn.generate(await tryOn.fetchPhoto(photoUrl), prompt);
      diag.generated = true;
      // A failed save still returns the image; the next view just generates again.
      await tryOn.store.put(key, image, "gemini").catch(() => {});
      return reply.header("content-type", "image/jpeg").header("cache-control", "private, max-age=86400").send(image);
    } catch (e) {
      const known = e instanceof HttpError ? e : null;
      if (!known) req.log.error({ errorName: (e as Error).name }, "tryon_unexpected");
      const err = known ?? new HttpError("internal_error", 500);
      diag.error = err.code;
      if (err.providerStatus) diag.providerStatus = err.providerStatus;
      return reply.code(err.status).send({ error: err.code });
    } finally {
      if (entered) tryOnGate?.leave();
      diag.durationMs = Math.round(performance.now() - started);
      req.log.info({ tryOnImage: diag }, "tryon_image");
    }
  });
}
